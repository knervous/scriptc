export default function getActiveElement(doc?: Document | null): Element | null | undefined {
    doc = doc || (typeof document !== 'undefined' ? document : undefined);
    if (typeof doc === 'undefined') {
        return null;
    }
    try {
        return doc.activeElement || doc.body;
    }
    catch (e: unknown) {
        return doc.body;
    }
}
