show("arraylike-map", () => from({ length: 2, 0: 1, 1: 2 } , (x, i) => x + i));
let closed = 0;
const closing= { [Symbol.iterator]() { let i = 0; return { next: () => ({ value: ++i, done: i > 5 }), return() { closed++; return {}; } }; } };
