var log = [];
const show = (label, f) => { try { log.push(label + "=" + JSON.stringify(f())); } catch (e) { log.push(label + "!" + (e instanceof TypeError ? "TypeError" : e instanceof RangeError ? "RangeError" : String(e))); } };
const from = Array.from;
