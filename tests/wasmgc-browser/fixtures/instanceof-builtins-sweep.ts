function t(v: unknown): string {
  const o: string[] = [];
  if (v instanceof Array) o.push("Array");
  if (v instanceof Object) o.push("Object");
  if (v instanceof Function) o.push("Function");
  if (v instanceof Map) o.push("Map");
  if (v instanceof Set) o.push("Set");
  if (v instanceof WeakMap) o.push("WeakMap");
  if (v instanceof WeakSet) o.push("WeakSet");
  if (v instanceof WeakRef) o.push("WeakRef");
  if (v instanceof Promise) o.push("Promise");
  if (v instanceof Date) o.push("Date");
  if (v instanceof RegExp) o.push("RegExp");
  if (v instanceof Error) o.push("Error");
  if (v instanceof TypeError) o.push("TypeError");
  if (v instanceof RangeError) o.push("RangeError");
  if (v instanceof SyntaxError) o.push("SyntaxError");
  if (v instanceof ReferenceError) o.push("ReferenceError");
  if (v instanceof EvalError) o.push("EvalError");
  if (v instanceof URIError) o.push("URIError");
  if (v instanceof AggregateError) o.push("AggregateError");
  if (v instanceof ArrayBuffer) o.push("ArrayBuffer");
  if (v instanceof SharedArrayBuffer) o.push("SharedArrayBuffer");
  if (v instanceof DataView) o.push("DataView");
  if (v instanceof Uint8Array) o.push("Uint8Array");
  if (v instanceof Uint8ClampedArray) o.push("Uint8ClampedArray");
  if (v instanceof Int8Array) o.push("Int8Array");
  if (v instanceof Uint16Array) o.push("Uint16Array");
  if (v instanceof Int16Array) o.push("Int16Array");
  if (v instanceof Uint32Array) o.push("Uint32Array");
  if (v instanceof Int32Array) o.push("Int32Array");
  if (v instanceof Float32Array) o.push("Float32Array");
  if (v instanceof Float64Array) o.push("Float64Array");
  if (v instanceof BigInt64Array) o.push("BigInt64Array");
  if (v instanceof BigUint64Array) o.push("BigUint64Array");
  if (v instanceof Boolean) o.push("Boolean");
  if (v instanceof Number) o.push("Number");
  if (v instanceof String) o.push("String");
  if (v instanceof Symbol) o.push("Symbol");
  if (v instanceof BigInt) o.push("BigInt");
  if (v instanceof URL) o.push("URL");
  if (v instanceof URLSearchParams) o.push("URLSearchParams");
  if (v instanceof Blob) o.push("Blob");
  if (v instanceof EventTarget) o.push("EventTarget");
  if (v instanceof Event) o.push("Event");
  if (v instanceof AbortController) o.push("AbortController");
  if (v instanceof AbortSignal) o.push("AbortSignal");
  if (v instanceof TextEncoder) o.push("TextEncoder");
  if (v instanceof TextDecoder) o.push("TextDecoder");
  if (v instanceof Headers) o.push("Headers");
  if (v instanceof Request) o.push("Request");
  if (v instanceof Response) o.push("Response");
  if (v instanceof ReadableStream) o.push("ReadableStream");
  return o.join(',');
}
